"""Script to generate `crates/ty_python_semantic/src/types/string_ops/titlecase.rs`.

The table lists every character whose Python titlecase mapping (`str.title` of the single
character) differs from its uppercase mapping (`str.upper`), as used by `str.capitalize`.

Usage: `uv run scripts/generate_ty_titlecase_table.py` from the repository root.
"""

from __future__ import annotations

import subprocess
import sys
import unicodedata
from pathlib import Path

MODULE_CRATE = "ty_python_semantic"
MODULE_PATH = (
    Path("crates") / MODULE_CRATE / "src" / "types" / "string_ops" / "titlecase.rs"
)


def rust_char(c: str) -> str:
    return f"'\\u{{{ord(c):x}}}'"


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in s) + '"'


def generate_module() -> None:
    entries = []
    for code_point in range(sys.maxunicode + 1):
        c = chr(code_point)
        title = c.title()
        if title != c.upper():
            entries.append((c, title))

    with MODULE_PATH.open("w", encoding="utf-8", newline="\n") as f:
        f.write(
            f"""\
//! This file is generated by `scripts/generate_ty_titlecase_table.py`.
//! Do not modify it manually!
//!
//! Generated with Python {sys.version_info.major}.{sys.version_info.minor} \
(Unicode {unicodedata.unidata_version}).

/// Characters whose titlecase mapping differs from their uppercase mapping, sorted by
/// character.
pub(super) static TITLECASE_EXCEPTIONS: &[(char, &str)] = &[
"""
        )
        for c, title in entries:
            f.write(f"    ({rust_char(c)}, {rust_str(title)}),\n")
        f.write("];\n")

    subprocess.run(["cargo", "fmt", "--package", MODULE_CRATE], check=True)


if __name__ == "__main__":
    generate_module()
